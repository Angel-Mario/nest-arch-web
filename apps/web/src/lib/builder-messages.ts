export const getDatabaseDescription = (
  database: string,
  locale: keyof typeof builderMessages
): string | undefined => {
  const translation = builderMessages[locale];
  if (database === "mongodb") {
    return translation.mongoDescription;
  }
  if (database === "sqlserver") {
    return translation.sqlServerDescription;
  }
  return undefined;
};

export const getAuthDescription = (
  auth: string,
  locale: keyof typeof builderMessages
): string | undefined => {
  const translation = builderMessages[locale];
  if (auth === "passport") {
    return translation.passportDescription;
  }
  if (auth === "better-auth") {
    return translation.betterAuthDescription;
  }
  return undefined;
};
